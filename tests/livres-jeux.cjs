const assert = require('node:assert/strict');

module.exports = function checkBooksAndGames(boot) {
  const fixture = {name:'Camille',introSeen:true,scene:4,xp:38,completed:[0,1,3],skipped:[2],attempts:{2:3},words:['你好','你','好','您','谢谢','妈妈']};
  const play = boot(fixture);
  const json = (game,code) => JSON.parse(game.run('JSON.stringify('+code+')'));
  const html = game => game.nodes.get('#app').innerHTML;
  play.run("switchTab('campagne')");
  assert.equal((html(play).match(/class="book-episode"/g)||[]).length,10);
  assert.equal((html(play).match(/<li>/g)||[]).length,60);
  assert(html(play).includes('onclick="replayScene(2)"') && !html(play).includes('onclick="replayScene(4)"'));
  play.run('replayEpisode(10);replayScene(59);startSceneReplay([59])');
  assert.equal(play.run('state.sceneReplay'),undefined);
  play.run('replayEpisode(1)');
  assert.deepEqual(json(play,'state.sceneReplay.queue'),[0,1,2,3]);
  play.run("selected='0';validate();validate()");
  assert.equal(play.run('state.xp'),40);
  assert.equal(play.run('state.scene'),4);
  assert.deepEqual(json(play,'state.completed'),fixture.completed);
  const reload=boot(JSON.parse(play.saved.get('dragonjade-v02')));
  assert.deepEqual(json(play,'state.sceneReplay.order'),json(reload,'state.sceneReplay.order'));
  assert.deepEqual(json(reload,'state.sceneReplay.order').slice().sort(),[0,1,2]);
  assert.deepEqual([...html(reload).matchAll(/onclick="selectAnswer\('(\d)'\)"/g)].map(m=>Number(m[1])),json(reload,'state.sceneReplay.order'));
  assert(html(reload).includes('Rejeu réussi · +2 XP'));
  reload.run('validate();advanceSceneReplay()');
  assert.equal(reload.run('state.xp'),40);
  assert.equal(reload.run('activeSceneIndex()'),1);
  reload.run("selected='2';validate();validate();validate()");
  assert.equal(reload.run('state.sceneReplay.result'),'passed');
  assert.equal(reload.run('state.xp'),40);
  reload.run("leaveSceneReplay('aventure')");
  assert.equal(reload.run('state.scene'),4);
  assert(html(reload).includes('Scène 5/6'));
  assert.deepEqual(json(reload,'state.attempts'),{2:3});
  assert.equal(reload.run('state.sceneReplay'),undefined);
  reload.run("replayScene(2);selected='0';validate();nextScene()");
  assert.equal(reload.run('state.xp'),42);
  assert(reload.run('scenes[2].words.every(w=>state.words.includes(w))'));
  assert.equal(reload.run('tab'),'campagne');
  assert.deepEqual(json(reload,'state.skipped'),[2]);

  const legacy=boot({introSeen:true,scene:0,xp:91,completed:[0,5],skipped:[],replayRewards:[0,1,3,4],clueScenes:[0,1,2,3,4,5]});
  assert.deepEqual(json(legacy,'state.completed'),[0,1,3,4,5]);
  assert.deepEqual(json(legacy,'state.skipped'),[2]);
  assert.equal(legacy.run('state.scene'),6);
  assert.equal(legacy.run('state.xp'),91);
  const replayAudio=boot(fixture);
  replayAudio.run("replayScene(0);var heard=[];playMandarinTurns=turns=>heard.push(turns.map(t=>t.zh));speakScene(true);speakSceneTurn(0)");
  assert.equal(replayAudio.run('heard[0][0]'),replayAudio.run('scenes[0].options[0][0]'));
  assert.equal(replayAudio.run('heard[1][0]'),replayAudio.run('sceneTurns(0,scenes[0])[0].zh'));

  for (const [kind,xp] of [['pairs',10],['echo',40],['brush',80],['envoy',120]]) {
    const g=boot({...fixture,xp:xp-1});
    g.run(`startJadeGame('${kind}')`);assert.equal(g.run('jadeGame'),null);
    g.run(`state.xp++;startJadeGame('${kind}')`);assert.equal(g.run('jadeGame.kind'),kind);
    assert.equal(g.run('state.xp'),xp);
  }
  const noWords=boot({introSeen:true,xp:180,words:[]});
  noWords.run("startJadeGame('brush');startJadeGame('pairs')");
  assert.equal(noWords.run('jadeGame'),null);
  const game=boot({...fixture,xp:120});
  game.run("startJadeGame('pairs')");
  assert(game.run('jadeGame.rounds.every(w=>state.words.includes(w[0]))'));
  assert(!html(game).includes('aria-label="bonjour"'));
  game.run('turnJadeCard(0);turnJadeCard(0)');
  assert.equal(game.run('jadeGame.open.length'),1);
  game.run('turnJadeCard(jadeGame.cards.findIndex(c=>c.pair!==jadeGame.cards[0].pair));turnJadeCard(0)');
  assert.equal(game.run('jadeGame.moves'),1);
  game.run('hideJadeCards();for(let i=0;i<jadeGame.rounds.length;i++){jadeGame.cards.forEach((c,j)=>{if(c.pair===i)turnJadeCard(j)})}');
  assert(html(game).includes('Partie terminée'));
  assert.equal(game.run('jadeGame.moves'),game.run('jadeGame.rounds.length+1'));

  game.run("startJadeGame('echo')");
  assert(game.run('jadeGame.pinyinMode'));
  assert(game.run('jadeGame.rounds.every(r=>r.choices.length>=2 && r.choices.every(c=>state.words.includes(c[0])))'));
  assert(game.run("!differentSounds(['他','tā','il'],['她','tā','elle'])"));
  game.run('answerEcho(jadeGame.rounds[0].choices.findIndex(c=>c!==jadeGame.rounds[0].word));answerEcho(0);nextGameRound()');
  assert.equal(game.run('jadeGame.answers.length'),1);
  game.run('while(jadeGame.index<jadeGame.rounds.length){const r=jadeGame.rounds[jadeGame.index];answerEcho(r.choices.indexOf(r.word));nextGameRound()}');
  assert(html(game).includes('Tes mots à revoir'));
  game.run("startJadeGame('echo',true)");
  assert.equal(game.run('jadeGame.rounds.length'),1);
  game.run("window.speechSynthesis={getVoices:()=>[{lang:'zh-CN'}],cancel(){},speak(){},resume(){}};window.SpeechSynthesisUtterance=class{};var SpeechSynthesisUtterance=window.SpeechSynthesisUtterance;switchEchoMode(false)");
  assert(!game.run('jadeGame.pinyinMode'));
  assert(html(game).includes('Écouter le mot'));

  const brush=boot({introSeen:true,xp:80,words:['妈妈','好']});
  brush.run("startJadeGame('brush');jadeGame.index=jadeGame.rounds.findIndex(r=>r.word[0]==='妈妈');prepareGameRound();render()");
  brush.run("chooseGameTile(jadeGame.tiles.indexOf('妈'));chooseGameTile(jadeGame.tiles.indexOf('妈'))");
  assert.equal(brush.run('jadeGame.draft'),'妈');
  brush.run("undoGameTile();jadeGame.tiles.forEach((c,i)=>{if(c==='妈')chooseGameTile(i)});writtenGameAnswer();writtenGameAnswer()");
  assert.equal(brush.run('jadeGame.answers.length'),1);
  assert(brush.run('jadeGame.feedback.ok'));
  brush.run("startJadeGame('brush');jadeGame.keyboard=true;jadeGame.draft='下雨';writtenGameAnswer()");
  assert(!brush.run('jadeGame.feedback.ok'));
  brush.run("startJadeGame('brush');jadeGame.keyboard=true;jadeGame.draft=jadeGame.rounds[0].word[0];writtenGameAnswer()");
  assert(brush.run('jadeGame.feedback.ok'));
  assert.equal(brush.run('state.xp'),80);

  const oral=boot({...fixture,xp:120});
  oral.run("startJadeGame('envoy');revealEnvoy();finishGameAnswer(true,true)");
  assert(oral.run('jadeGame.feedback.selfRated'));
  oral.run("nextGameRound();window.isSecureContext=true;window.SpeechRecognition=class{start(){}stop(){}abort(){}};startEnvoyMic()");
  oral.run("gameMic.onresult({resultIndex:0,results:[Object.assign([{transcript:'外星'},{transcript:jadeGame.rounds[jadeGame.index].word[0]}],{isFinal:true})]})");
  assert(oral.run('jadeGame.feedback.ok && !jadeGame.feedback.selfRated'));
  oral.run("nextGameRound();startEnvoyMic();gameMic.onerror({error:'not-allowed'})");
  assert(html(oral).includes('Microphone refusé'));
  oral.run("startEnvoyMic();const late=gameMic.onresult;switchTab('carnet');late({resultIndex:0,results:[[{transcript:'好'}]]})");
  assert.equal(oral.run('gameMic'),null);
  assert.equal(oral.run('jadeGame.answers.length'),2);
  oral.run("startEnvoyMic()");
  assert.equal(oral.run('gameMic'),null);
  oral.run("switchTab('campagne')");
  for(let n=0;n<3;n++)oral.run("startEnvoyMic();gameMic.onresult({results:[[{transcript:'外星'}]]})");
  assert.equal(oral.run('jadeGame.feedback.ok'),false);
  oral.run("switchTab('campagne');while(jadeGame.index<jadeGame.rounds.length){if(!jadeGame.feedback){revealEnvoy();finishGameAnswer(true,true)}nextGameRound()}");
  assert(html(oral).includes('en autoévaluation'));
  assert.equal(oral.run('state.xp'),120);
  assert.deepEqual(json(oral,'state.words'),fixture.words);
  console.log('PASS: 60 listed scenes, scoped replays, legacy saves, +2 XP exactly once, four thresholds, learned-only games, writing, audio and microphone fallbacks');
};
